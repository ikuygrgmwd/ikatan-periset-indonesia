export function polygonPath(coordinates: number[][], project = mapPoint) {
  return (
    coordinates
      .map(
        ([lon, lat], i) =>
          `${i ? "L" : "M"}${project(lon, lat)
            .map((n) => n.toFixed(1))
            .join(",")}`,
      )
      .join(" ") + " Z"
  );
}
